class MyHomePage extends StatelessWidget {
  const MyHomePage({super.key});
  static final AccelerometerSensorUtil _accelerometerSensorUtil =
      AccelerometerSensorUtil();

  @override
  Widget build(BuildContext context) {
    // This method is rerun every time setState is called, for instance as done
    // by the _incrementCounter method above.
    //
    // The Flutter framework has been optimized to make rerunning build methods
    // fast, so that you can just rebuild anything that needs updating rather
    // than having to individually change instances of widgets.
    return Scaffold(
      appBar: AppBar(
        backgroundColor: Theme.of(context).colorScheme.inversePrimary,
        title: Text('Accelerometer Data'),
      ),
      body: Center(
        // Center is a layout widget. It takes a single child and positions it
        // in the middle of the parent.
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            StreamBuilder(
                stream: _accelerometerSensorUtil.sensorStream,
                builder: (context, snapshot) {
                  return Column(
                    children: [
                      Text("X: ${snapshot.data?.x.toString() ?? '0'}"),
                      Text("Y: ${snapshot.data?.y.toString() ?? '0'}"),
                      Text("Z: ${snapshot.data?.z.toString() ?? '0'}"),
                      Text(snapshot.data?.z.toString() ?? '0'),
                    ],
                  );
                }),
          ],
        ),
      ),
    );
  }
}
